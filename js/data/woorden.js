/** Alle woorden met deze beginletter. */
export function woordenMetLetter(letter) {
  return woorden.filter((w) => w.letter === letter);
}

/** Pad naar het plaatje van een woord, relatief aan de site-root. */
export function plaatjePad(woord) {
  return `assets/img/${woord.cp}.svg`;
}

/** Staat dit woord standaard aan? (ontbrekende vlag = ja) */
export function standaardAan(woord) {
  return woord.standaard !== false;
}

/** Hoeveel bruikbare woorden heeft deze letter? */
export function aantalPerLetter(letter) {
  return woordenMetLetter(letter).length;
}
